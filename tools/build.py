#!/usr/bin/env python3
"""Build assets/data.js for the static CTF board.

Reads every challenges/<category>/<slug>/challenge.json plus data/archive.json
and writes assets/data.js. Flags are stored only as salted SHA-256 hashes so
they are not readable in the page source (the writeups still contain them).

    python tools/build.py
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SALT = "njccic9:"

CTF = {
    "name": "NJCCIC Group 9",
    "description": "NJCCIC Advanced Internship Group 9 CTF",
    "repo": "https://github.com/aidanlenahan/njccic9-ctf-archive",
    "webuc": "https://aidanlenahan.github.io/njccic9-ctf",
}

CATEGORY_ORDER = ["Welcome", "Web", "Image", "Website Under Construction", "Cryptography", "OSINT"]


def flag_hash(flag: str, case_insensitive: bool) -> str:
    if case_insensitive:
        flag = flag.lower()
    return hashlib.sha256((SALT + flag.strip()).encode()).hexdigest()


def main() -> None:
    challenges, writeups = [], []
    for meta in sorted(ROOT.glob("challenges/*/*/challenge.json")):
        c = json.loads(meta.read_text(encoding="utf-8"))
        base = meta.parent.relative_to(ROOT).as_posix()
        writeups.append({
            "id": c["id"], "name": c["name"], "category": c["category"], "value": c["value"],
            "hidden": c.get("hidden", False), "writeup": f"{base}/README.md",
        })
        if c.get("hidden"):
            continue
        challenges.append({
            "id": c["id"],
            "name": c["name"],
            "category": c["category"],
            "value": c["value"],
            "description": c["description"],
            "connection_info": c.get("connection_info"),
            "case_insensitive": c.get("case_insensitive", False),
            "flag_sha256": flag_hash(c["flag"], c.get("case_insensitive", False)),
            "files": [f"{base}/{f}" for f in c.get("files", [])],
            "hints": [
                {"id": i + 1, "title": h.get("title", ""), "content": h["content"], "cost": h.get("cost", 0)}
                for i, h in enumerate(c.get("hints", []))
            ],
            "writeup": f"{base}/README.md",
        })

    order = {name: i for i, name in enumerate(CATEGORY_ORDER)}
    key = lambda c: (order.get(c["category"], 99), c["value"], c["id"])
    challenges.sort(key=key)
    writeups.sort(key=key)

    archive = json.loads((ROOT / "data/archive.json").read_text(encoding="utf-8"))
    data = {"ctf": CTF, "salt": SALT, "challenges": challenges, "writeups": writeups, "archive": archive["users"]}

    out = ROOT / "assets/data.js"
    out.write_text(
        "// Generated by tools/build.py. Do not edit by hand.\n"
        "window.CTF_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {out.relative_to(ROOT)} with {len(challenges)} challenges")


if __name__ == "__main__":
    main()
